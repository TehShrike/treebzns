function card(c) {
	const body = c.markup.map((l) => '\t\t' + l).join('\n')
	return [
		`<!-- @dsCard group="${c.group}" -->`,
		'<!DOCTYPE html>',
		'<html lang="en">',
		'<head>',
		'\t<meta charset="UTF-8">',
		`\t<title>${c.name}</title>`,
		'\t<link rel="stylesheet" href="../../../styles.css">',
		'\t<style>',
		'\t\tbody { background: #008080; margin: 0; padding: 24px; font-family: Arial, sans-serif; }',
		'\t\t.ds-stack > * + * { margin-top: 16px; }',
		'\t</style>',
		'</head>',
		'<body>',
		'\t<div class="ds-stack">',
		body,
		'\t</div>',
		'</body>',
		'</html>',
		'',
	].join('\n')
}

function prompt(c) {
	return [
		c.summary,
		'',
		...c.notes,
		'',
		'## Markup',
		'',
		'```html',
		...c.markup,
		'```',
		'',
	].join('\n')
}

for (const c of components) {
	const dir = join(out, c.group, c.name)
	mkdirSync(dir, { recursive: true })
	writeFileSync(join(dir, `${c.name}.html`), card(c))
	writeFileSync(join(dir, `${c.name}.prompt.md`), prompt(c))
	writeFileSync(join(dir, `${c.name}.d.ts`), c.dts.join('\n') + '\n')
}
console.log(`wrote ${components.length} component card sets to ${out}`)

